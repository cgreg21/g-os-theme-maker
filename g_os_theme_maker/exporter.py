"""Export design tokens to GNOME Shell/St CSS using @define-color."""
from .model import ThemeTokens


def export_css(tokens: ThemeTokens) -> str:
    tokens.validate()
    overrides = tokens.component_overrides
    topbar = overrides.get("topbar", {})
    card = overrides.get("card", {})
    primary = overrides.get("primary_button", {})
    secondary = overrides.get("secondary_button", {})
    return f"""/* Generated by G-OS Theme Maker. Review against your GNOME Shell version. */
@define-color gom_background {tokens.background};
@define-color gom_surface {tokens.surface};
@define-color gom_foreground {tokens.foreground};
@define-color gom_muted {tokens.muted};
@define-color gom_accent {tokens.accent};
@define-color gom_border {tokens.border};

/* Starter component styles; adapt selectors to the target Shell release. */
.popup-menu-content, .modal-dialog {{
  color: @gom_foreground;
  background-color: @gom_surface;
  border: 1px solid @gom_border;
  border-radius: {tokens.radius}px;
  padding: {tokens.spacing}px;
  font-size: {tokens.font_size}px;
}}

.button {{
  color: @gom_foreground;
  background-color: @gom_surface;
  border-radius: {tokens.radius}px;
  padding: {tokens.spacing}px;
}}
.button:focus, .button:hover {{ background-color: @gom_accent; }}

/* Component-specific overrides. Add these classes to matching theme widgets. */
.gom-topbar {{
  color: {topbar.get("foreground", tokens.foreground)};
  background-color: {topbar.get("background", tokens.surface)};
  border-color: {topbar.get("border", tokens.border)};\n  border-radius: {topbar.get("radius", tokens.radius)}px;
  padding: {topbar.get("spacing", tokens.spacing)}px;
}}
.gom-card {{
  color: {card.get("foreground", tokens.foreground)};
  background-color: {card.get("background", tokens.surface)};
  border-color: {card.get("border", tokens.border)};
  border-radius: {card.get("radius", tokens.radius)}px;
  padding: {card.get("spacing", tokens.spacing) * 2}px;
}}
.gom-primary-button {{
  color: {primary.get("foreground", "#ffffff")};
  background-color: {primary.get("background", tokens.accent)};
  border-color: {primary.get("border", tokens.border)};\n  border-radius: {primary.get("radius", tokens.radius)}px;
  padding: {primary.get("spacing", tokens.spacing)}px;
}}
.gom-primary-button:hover {{ background-color: {primary.get("hover", tokens.accent)}; }}
.gom-primary-button:active {{ background-color: {primary.get("active", tokens.accent)}; }}
.gom-secondary-button {{
  color: {secondary.get("foreground", tokens.foreground)};
  background-color: {secondary.get("background", tokens.surface)};
  border-color: {secondary.get("border", tokens.border)};\n  border-radius: {secondary.get("radius", tokens.radius)}px;
  padding: {secondary.get("spacing", tokens.spacing)}px;
}}
.gom-secondary-button:hover {{ background-color: {secondary.get("hover", tokens.accent)}; }}
.gom-secondary-button:active {{ background-color: {secondary.get("active", tokens.accent)}; }}
"""