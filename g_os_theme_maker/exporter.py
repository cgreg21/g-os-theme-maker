"""Export design tokens to GNOME Shell/St CSS using @define-color."""
from .model import ThemeTokens


def export_css(tokens: ThemeTokens) -> str:
    tokens.validate()
    return f"""/* Generated by G-OS Theme Maker. Review against your GNOME Shell version. */
@define-color gom_background {tokens.background};
@define-color gom_surface {tokens.surface};
@define-color gom_foreground {tokens.foreground};
@define-color gom_muted {tokens.muted};
@define-color gom_accent {tokens.accent};
@define-color gom_border {tokens.border};

/* Starter component styles; adapt selectors to the target Shell release. */
.popup-menu-content, .modal-dialog {{
  color: @gom_foreground;
  background-color: @gom_surface;
  border: 1px solid @gom_border;
  border-radius: {tokens.radius}px;
  padding: {tokens.spacing}px;
  font-size: {tokens.font_size}px;
}}

.button {{
  color: @gom_foreground;
  background-color: @gom_surface;
  border-radius: {tokens.radius}px;
  padding: {tokens.spacing}px;
}}
.button:focus, .button:hover {{ background-color: @gom_accent; }}
"""