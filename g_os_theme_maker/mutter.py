"""Run an isolated nested GNOME Shell with a temporary theme preview extension."""
from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Sequence


_EXTENSION_UUID = "g-os-theme-preview@local"


class NestedShellController:
    def __init__(self, command: Sequence[str] | None = None) -> None:
        self.command = list(command or ("gnome-shell", "--nested", "--wayland"))
        self.process: subprocess.Popen[bytes] | None = None
        self._runtime: tempfile.TemporaryDirectory[str] | None = None

    @property
    def available(self) -> bool:
        return shutil.which("dbus-run-session") is not None and shutil.which(self.command[0]) is not None

    @property
    def running(self) -> bool:
        return self.process is not None and self.process.poll() is None

    def start(self, theme_css: str | None = None) -> None:
        if self.running:
            return
        if not self.available:
            raise RuntimeError(
                "Installe GNOME Shell et dbus-run-session pour lancer l'aperçu isolé."
            )

        self._runtime = tempfile.TemporaryDirectory(prefix="g-os-theme-preview-")
        root = Path(self._runtime.name)
        data_home = root / "data"
        config_home = root / "config"
        extension_dir = data_home / "gnome-shell" / "extensions" / _EXTENSION_UUID
        extension_dir.mkdir(parents=True)
        config_home.mkdir()
        (root / "dconf-profile").write_text(f"user-db:{root / 'dconf'}\n", encoding="utf-8")

        metadata = {
            "uuid": _EXTENSION_UUID,
            "name": "G-OS Theme Preview",
            "description": "Loads the temporary stylesheet generated by G-OS Theme Maker.",
            "shell-version": [str(version) for version in range(42, 52)],
        }
        (extension_dir / "metadata.json").write_text(
            json.dumps(metadata, indent=2) + "\n", encoding="utf-8"
        )
        (extension_dir / "extension.js").write_text(
            "import St from 'gi://St';\n"
            "import { Extension } from 'resource:///org/gnome/shell/extensions/extension.js';\n"
            "export default class ThemePreviewExtension extends Extension {\n"
            "  enable() {\n"
            "    this._theme = St.ThemeContext.get_for_stage(global.stage).get_theme();\n"
            "    this._stylesheet = this.dir.get_child('gnome-shell.css');\n"
            "    this._theme.load_stylesheet(this._stylesheet);\n"
            "  }\n"
            "  disable() {\n"
            "    if (this._theme && this._stylesheet)\n"
            "      this._theme.unload_stylesheet(this._stylesheet);\n"
            "    this._theme = null;\n"
            "    this._stylesheet = null;\n"
            "  }\n"
            "}\n",
            encoding="utf-8",
        )
        (extension_dir / "gnome-shell.css").write_text(theme_css or "", encoding="utf-8")

        env = {
            **__import__("os").environ,
            "XDG_DATA_HOME": str(data_home),
            "XDG_CONFIG_HOME": str(config_home),
            "DCONF_PROFILE": str(root / "dconf-profile"),
        }
        shell_command = "gsettings set org.gnome.shell enabled-extensions \"['" + _EXTENSION_UUID + "']\" && exec " + " ".join(self.command)
        try:
            self.process = subprocess.Popen(
                ["dbus-run-session", "--", "sh", "-c", shell_command],
                stdin=subprocess.DEVNULL,
                env=env,
            )
        except OSError:
            self._runtime.cleanup()
            self._runtime = None
            raise

    def stop(self) -> None:
        if self.running and self.process is not None:
            self.process.terminate()
            try:
                self.process.wait(timeout=3)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=2)
        self.process = None
        if self._runtime is not None:
            self._runtime.cleanup()
            self._runtime = None
